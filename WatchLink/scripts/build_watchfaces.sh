#!/usr/bin/env bash
# Builds the sample Watch Face Format watch face, validates it with Google's Watch Face Push
# validator (producing the validation token), and distributes the outputs.
# Run from WatchLink/ (CI does). Never fails the overall build because of the validator:
# on validation failure the token file contains VALIDATION_FAILED and the script exits 0.
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."

MARKETPLACE_PACKAGE="com.watchlink.companion"
VALIDATOR_FALLBACK_VERSION="1.0.0-alpha10"
MAVEN_BASE="https://dl.google.com/dl/android/maven2/com/google/android/wearable/watchface/validator/validator-push-cli"

OUT_DIR="build/watchfaces"
TOOLS_DIR="build/tools"
APK_OUT="$OUT_DIR/WatchLink-Classic-watchface.apk"
TOKEN_OUT="$OUT_DIR/WatchLink-Classic-watchface.token"
MOBILE_ASSETS="mobile/src/main/assets/watchfaces"
WEARFACE_ASSETS="wearfacepush/src/main/assets"
WEARFACE_RES="wearfacepush/src/main/res/values"

mkdir -p "$OUT_DIR" "$TOOLS_DIR" "$MOBILE_ASSETS" "$WEARFACE_ASSETS" "$WEARFACE_RES"

echo "==> Building sample watch face"
./gradlew --stacktrace :sample-watchface:assembleRelease

APK_SRC="$(ls -1 sample-watchface/build/outputs/apk/release/*.apk | head -n 1)"
[ -f "$APK_SRC" ] || { echo "ERROR: watch face APK not found" >&2; exit 1; }
cp "$APK_SRC" "$APK_OUT"
echo "APK: $APK_OUT ($(wc -c < "$APK_OUT") bytes)"
unzip -l "$APK_OUT" > "$OUT_DIR/watchface-contents.txt" || true

TOKEN="VALIDATION_FAILED"

validate() {
  local version jar url out token
  # Latest published version from maven-metadata.xml, else the fallback.
  version="$(curl -fsSL "$MAVEN_BASE/maven-metadata.xml" 2>/dev/null \
    | sed -n 's:.*<release>\(.*\)</release>.*:\1:p' | head -n 1 || true)"
  version="${version:-$VALIDATOR_FALLBACK_VERSION}"
  jar="$TOOLS_DIR/validator-push-cli-$version.jar"
  if [ ! -s "$jar" ]; then
    url="$MAVEN_BASE/$version/validator-push-cli-$version.jar"
    echo "==> Downloading validator $version from $url"
    if ! curl -fsSL -o "$jar" "$url"; then
      rm -f "$jar"
      if [ "$version" != "$VALIDATOR_FALLBACK_VERSION" ]; then
        version="$VALIDATOR_FALLBACK_VERSION"
        jar="$TOOLS_DIR/validator-push-cli-$version.jar"
        curl -fsSL -o "$jar" "$MAVEN_BASE/$version/validator-push-cli-$version.jar" || { rm -f "$jar"; return 1; }
      else
        return 1
      fi
    fi
  fi
  echo "==> Running validator $version"
  mkdir -p "$OUT_DIR"
  local rc=0
  out="$(java -jar "$jar" --apk_path="$APK_OUT" --package_name="$MARKETPLACE_PACKAGE" 2>&1)" || rc=$?
  { echo "validator $version exit=$rc"; echo "$out"; } > "$OUT_DIR/validator.log"
  echo "$out"
  [ "$rc" -eq 0 ] || return 1
  # Output format: a line like "Validation token: <token>" (fall back to a lone token-looking line).
  token="$(printf '%s\n' "$out" | sed -n 's/^.*[Tt]oken[^:=]*[:=][[:space:]]*\([^[:space:]]\{16,\}\)[[:space:]]*$/\1/p' | tail -n 1)"
  if [ -z "$token" ]; then
    token="$(printf '%s\n' "$out" | grep -E '^[A-Za-z0-9+/=_-]{16,}$' | tail -n 1 || true)"
  fi
  [ -n "$token" ] || { echo "Could not find a validation token in validator output" >&2; return 1; }
  TOKEN="$token"
}

if ! validate; then
  echo "WARNING: watch face validation failed - writing VALIDATION_FAILED as token." >&2
  echo "WARNING: the phone app will not be able to push the sample watch face." >&2
  TOKEN="VALIDATION_FAILED"
fi

printf '%s' "$TOKEN" > "$TOKEN_OUT"
echo "Token file: $TOKEN_OUT"

echo "==> Distributing outputs"
# Phone app: sample watch face offered for pushing.
cp "$APK_OUT" "$MOBILE_ASSETS/sample.apk"
cp "$TOKEN_OUT" "$MOBILE_ASSETS/sample.token"

# Watch app (marketplace role): mandatory default watch face + its token.
# The classic face already follows the <marketplace>.watchfacepush.<name> rule, so it doubles as default.
cp "$APK_OUT" "$WEARFACE_ASSETS/default_watchface.apk"
cp "$TOKEN_OUT" "$WEARFACE_ASSETS/default_watchface_token.txt"
cat > "$WEARFACE_RES/default_wf_token.xml" <<XML
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/build_watchfaces.sh. -->
<resources>
    <string name="default_wf_token" translatable="false">$TOKEN</string>
</resources>
XML

echo "Done. token=${TOKEN:0:12}..."
exit 0
